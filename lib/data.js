// 3. Функція для отримання одного товару за ID (без змін)
export function getProductById(id) {
  return products.find(product => product.id == id);
}

// 4. ФУНКЦІЯ ДЛЯ ОТРИМАННЯ КАТЕГОРІЙ (ОНОВЛЕНО)
export function getCategories() {
  const categories = products.map(p => p.category);
  return [...new Set(categories.filter(Boolean))];
}

// 5. SLUG MAPPING AND HELPERS
export const categorySlugs = {
  "Стільці": "chairs",
  "Столи": "tables",
  "Дивани": "sofas",
  "Офісні меблі": "office-furniture"
};

// Reverse mapping for internal use if needed
export const slugToCategory = Object.fromEntries(
  Object.entries(categorySlugs).map(([name, slug]) => [slug, name])
);

export function getSlugByCategory(categoryName) {
  return categorySlugs[categoryName] || categoryName.toLowerCase();
}

export function getCategoryBySlug(slug) {
  return slugToCategory[slug];
}

export function getProductsByCategorySlug(slug) {
  const categoryName = getCategoryBySlug(slug);
  if (!categoryName) return [];
  return products.filter(p => p.category === categoryName);
}